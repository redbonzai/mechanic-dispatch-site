/**
 * Writes src/environments/api-base.generated.ts from API_BASE_URL.
 * Resolution order: process.env.API_BASE_URL → web/.env.local → repo root .env → default.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.join(__dirname, '..');
const outFile = path.join(webRoot, 'src/environments/api-base.generated.ts');

function stripTrailingSlashes(u) {
  return u.replace(/\/+$/, '');
}

function readEnvFileKey(filePath, key) {
  if (!fs.existsSync(filePath)) return null;
  const text = fs.readFileSync(filePath, 'utf8');
  const line = text.split(/\r?\n/).find((l) => {
    const t = l.trim();
    return t.startsWith(`${key}=`) && !t.startsWith('#');
  });
  if (!line) return null;
  let v = line.slice(line.indexOf('=') + 1).trim();
  if (
    (v.startsWith('"') && v.endsWith('"')) ||
    (v.startsWith("'") && v.endsWith("'"))
  ) {
    v = v.slice(1, -1);
  }
  return v || null;
}

/** When unset, use this in Vercel builds so we never ship localhost:3000 to browsers. */
const VERCEL_DEFAULT_API_BASE = 'https://api.mechanicdispatch.com';

function resolveApiBaseUrl() {
  const fromEnv = process.env.API_BASE_URL?.trim();
  if (fromEnv) return stripTrailingSlashes(fromEnv);

  const fromWebLocal = readEnvFileKey(path.join(webRoot, '.env.local'), 'API_BASE_URL');
  if (fromWebLocal) return stripTrailingSlashes(fromWebLocal);

  const fromRootEnv = readEnvFileKey(path.join(webRoot, '..', '.env'), 'API_BASE_URL');
  if (fromRootEnv) return stripTrailingSlashes(fromRootEnv);

  // Vercel sets VERCEL=1 during `pnpm build` when API_BASE_URL is not configured.
  if (process.env.VERCEL === '1') {
    return stripTrailingSlashes(VERCEL_DEFAULT_API_BASE);
  }

  return 'http://localhost:3000';
}

const url = resolveApiBaseUrl();
const contents = `/* Generated by scripts/generate-api-base.mjs — do not edit. */
export const API_BASE_URL = ${JSON.stringify(url)};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, contents, 'utf8');
// eslint-disable-next-line no-console -- build feedback
console.log('[generate-api-base] API_BASE_URL ->', url);
